def era_rank(table: dict[str, int | None], period: str) -> int | None:
    """period/文献名 → 排序年；未知返回 None（调用方排最后）。"""
    return table.get((period or "").strip())


def sort_key_with_year(year: int | None, fallback) -> tuple:
    """有年按年排，未知的排最后、按 fallback（条目号等）平局判定。"""
    return (0, year, fallback) if year is not None else (1, 0, fallback)
